"""Reproduce compact, separate scientist poses; no labels/meters/frames in assets."""
from pathlib import Path
import hashlib,json,sys
from PIL import Image,__version__
ROOT=Path(__file__).resolve().parents[1];SRC=ROOT/'assets/home-scientists/poses_source.png'
W,H=90,56
def clean(cell):
    # Discard tiny alpha speckles from the generated sheet, retaining detached bubbles.
    alpha=cell.getchannel('A');mask=bytearray(1 if v>=160 else 0 for v in alpha.tobytes());cw,ch=cell.size
    out=bytearray(cw*ch)
    for start in range(cw*ch):
        if not mask[start]:continue
        stack=[start];mask[start]=0;component=[]
        while stack:
            p=stack.pop();component.append(p);x=p%cw;y=p//cw
            for q in ((p-1 if x else -1),(p+1 if x+1<cw else -1),(p-cw if y else -1),(p+cw if y+1<ch else -1)):
                if q>=0 and mask[q]:mask[q]=0;stack.append(q)
        if len(component)>=128:
            for p in component:out[p]=255
    cell.putalpha(Image.frombytes('L',(cw,ch),bytes(out)));return cell
def generate(out):
    out.mkdir(parents=True,exist_ok=True);im=Image.open(SRC).convert('RGBA');cw,ch=im.width//4,im.height//3
    assert im.size==(1448,1086)
    cells=[[clean(im.crop((c*cw,r*ch,(c+1)*cw,(r+1)*ch))) for r in range(3)] for c in range(4)]
    frames=[]
    for column in cells:
        boxes=[p.getbbox() for p in column];box=(min(b[0] for b in boxes),min(b[1] for b in boxes),max(b[2] for b in boxes),max(b[3] for b in boxes))
        scale=min(W/(box[2]-box[0]),H/(box[3]-box[1]));size=(round((box[2]-box[0])*scale),round((box[3]-box[1])*scale))
        for cell in column:
            a=cell.crop(box).resize(size,Image.Resampling.LANCZOS);canvas=Image.new('RGB',(W,H),'black');canvas.paste(a,((W-size[0])//2,H-size[1]),a);frames.append(canvas)
    strip=Image.new('RGB',(W*12,H))
    for i,p in enumerate(frames):strip.paste(p,(W*i,0))
    quant=strip.quantize(colors=256,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE)
    pal=quant.getpalette();words=[((pal[i*3]>>3)<<11)|((pal[i*3+1]>>2)<<5)|(pal[i*3+2]>>3) for i in range(256)]
    blob=bytearray();offsets=[0];hashes=[];contact=Image.new('RGB',(W*4,H*3))
    for i in range(12):
        pix=quant.crop((i*W,0,(i+1)*W,H)).tobytes();j=0
        while j<len(pix):
            n=1
            while j+n<len(pix) and pix[j+n]==pix[j] and n<128:n+=1
            if n>=3:blob.extend((128+n-1,pix[j]));j+=n
            else:
                a=j;j+=n
                while j<len(pix) and j-a<128:
                    if j+2<len(pix) and pix[j]==pix[j+1]==pix[j+2]:break
                    j+=1
                blob.append(j-a-1);blob.extend(pix[a:j])
        offsets.append(len(blob));rgb=b''.join(words[k].to_bytes(2,'big') for k in pix);hashes.append(hashlib.sha256(rgb).hexdigest())
        preview=Image.new('RGB',(W,H));preview.putdata([(((words[k]>>11)&31)*255//31,((words[k]>>5)&63)*255//63,(words[k]&31)*255//31) for k in pix]);contact.paste(preview,((i//3)*W,(i%3)*H))
    def arr(typ,name,v):return f'static const {typ} {name}[{len(v)}] = {{\n'+''.join('    '+','.join(map(str,v[i:i+24]))+',\n' for i in range(0,len(v),24))+'};\n'
    text='/* Generated by tools/gen_home_sprites.py. Poses only, no UI elements. */\n#pragma once\n#define HOME_SPRITE_W 90u\n#define HOME_SPRITE_H 56u\n'
    text+=arr('uint16_t','HOME_SPRITE_PALETTE',[((v&255)<<8)|(v>>8) for v in words])+arr('uint32_t','HOME_SPRITE_OFFSETS',offsets)+arr('uint8_t','HOME_SPRITE_DATA',list(blob))
    (out/'home_sprites.h').write_text(text);contact.save(out/'poses_native.png')
    info=dict(source_sha256=hashlib.sha256(SRC.read_bytes()).hexdigest(),pillow=__version__,sprite_size=[W,H],order='channel-major: idle,active,energetic',frames=12,palette_bytes=512,offset_bytes=52,encoded_bytes=len(blob),total_asset_bytes=len(blob)+564,frame_rgb565_sha256=hashes)
    (out/'sprites.json').write_text(json.dumps(info,indent=2)+'\n');print(json.dumps(info))
if __name__=='__main__':generate(Path(sys.argv[1]) if len(sys.argv)>1 else SRC.parent)
