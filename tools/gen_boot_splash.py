"""Reproduce the indexed RGB565 splash; never rewrite the approved source."""
from pathlib import Path
import hashlib,json,struct,sys
from PIL import Image,ImageOps,ImageDraw,ImageFont,__version__
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'assets/startup-splash/coffee_grains_boot_splash_source.png'
HASH='68e4a4c9190aeb789f88c408c6d67dfc71b68bf92f742bc4ea205ac8cfebed30'
CREDIT='CREATED BY Auberg1ne'
def generate(out):
    assert hashlib.sha256(SOURCE.read_bytes()).hexdigest()==HASH
    out.mkdir(parents=True,exist_ok=True)
    source=Image.open(SOURCE).convert('RGB')
    art=ImageOps.contain(source,(240,192),Image.Resampling.LANCZOS)
    canvas=Image.new('RGB',(240,240),'black');canvas.paste(art,((240-art.width)//2,12))
    font=ImageFont.truetype(str(ROOT/'assets/fonts/InterTight[wght].ttf'),11)
    d=ImageDraw.Draw(canvas);box=d.textbbox((0,0),CREDIT,font=font)
    d.text(((240-(box[2]-box[0]))//2,222-box[1]),CREDIT,font=font,fill='white')
    im=canvas.quantize(colors=256,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE)
    pal=im.getpalette();palette=[]
    for k in range(256):
        r,g,b=pal[k*3:k*3+3];palette.append(((r>>3)<<11)|((g>>2)<<5)|(b>>3))
    pixels=im.tobytes();packed=bytearray();offsets=[]
    for y in range(240):
        offsets.append(len(packed));row=pixels[y*240:(y+1)*240];i=0
        while i<240:
            run=1
            while i+run<240 and row[i+run]==row[i] and run<128:run+=1
            if run>=3:
                packed.extend((128+run-1,row[i]));i+=run
            else:
                a=i;i+=run
                while i<240 and i-a<128:
                    if i+2<240 and row[i]==row[i+1]==row[i+2]:break
                    i+=1
                packed.append(i-a-1);packed.extend(row[a:i])
    offsets.append(len(packed));assert len(packed)<65536
    rgb=b''.join(struct.pack('>H',palette[v]) for v in pixels)
    # Preview exactly the RGB565 values sent to the display, not pre-quantization RGB.
    preview=Image.new('RGB',(240,240));preview.putdata([(((v>>11)&31)*255//31,((v>>5)&63)*255//63,(v&31)*255//31) for v in (palette[k] for k in pixels)])
    preview.save(out/'boot_splash_240.png')
    def array(typ,name,values):
        return f'static const {typ} {name}[{len(values)}] = {{\n'+''.join('    '+','.join(map(str,values[i:i+24]))+',\n' for i in range(0,len(values),24))+'};\n'
    # DMA requires RAM and panel-byte-order pixels; palette stores byte-swapped words.
    header='/* Generated by tools/gen_boot_splash.py; approved source remains unchanged. */\n#pragma once\n'
    header+=array('uint16_t','BOOT_ART_PALETTE',[((v&255)<<8)|(v>>8) for v in palette])
    header+=array('uint16_t','BOOT_ART_ROWS',offsets)+array('uint8_t','BOOT_ART_DATA',list(packed))
    (out/'boot_splash.h').write_text(header)
    meta=dict(source_sha256=HASH,source_size=list(source.size),display=[240,240],art_rect=[0,12,art.width,art.height],credit=CREDIT,pillow=__version__,rgb565_sha256=hashlib.sha256(rgb).hexdigest(),encoded_bytes=len(packed),palette_bytes=512,row_table_bytes=482,total_asset_bytes=len(packed)+994,raw_rgb565_bytes=len(rgb))
    (out/'conversion.json').write_text(json.dumps(meta,indent=2)+'\n')
    print(json.dumps(meta))
if __name__=='__main__':generate(Path(sys.argv[1]) if len(sys.argv)>1 else SOURCE.parent)
