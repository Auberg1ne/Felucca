"""Independent standard Tukey(alpha=0.5) Q15 table; no GRAINE source copied."""
import argparse, math
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
v=[]
for i in range(129):
 t=i/256
 w=0.5*(1-math.cos(4*math.pi*t)) if t<0.25 else 1.0
 v.append(int(math.floor(w*32767+0.5)))
v+=v[-2::-1]
s='/* SPDX-License-Identifier: GPL-3.0-only */\n/* Generated by tools/gen_grain_tukey.py; standard Tukey alpha=0.5, Q15. */\n#pragma once\n#include <stdint.h>\nstatic const int16_t GR_TUKEY[257] = {\n'
s+=''.join('    '+', '.join(map(str,v[i:i+16]))+',\n' for i in range(0,257,16))+'};\n'
s+='''/* Convex Q15 interpolation, floor-rounded without negative signed shifts.
 * |delta| <= 32767 and f <= 32767: product fits int32. */
static inline int32_t gr_tukey_win(uint32_t phase)
{
    uint32_t i=phase>>24, f=(phase>>9)&32767u;
    int32_t product=(GR_TUKEY[i+1u]-GR_TUKEY[i])*(int32_t)f;
    int32_t delta=product>=0?product/32768:-((-product+32767)/32768);
    return GR_TUKEY[i]+delta;
}
'''
out=Path(__file__).resolve().parents[1]/'firmware/src/grain_tukey.h'
if a.check: assert out.read_text()==s,'Tukey table is stale'
else: out.write_text(s)
